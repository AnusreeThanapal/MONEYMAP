def load_font(size):
    """Load a system monospace font, fall back to default."""
    candidates = [
        "C:/Windows/Fonts/consola.ttf",
        "C:/Windows/Fonts/cour.ttf",
        "C:/Windows/Fonts/arial.ttf",
    ]
    for p in candidates:
        if os.path.exists(p):
            return ImageFont.truetype(p, size)
    return ImageFont.load_default()


def fmt_inr(amount: float) -> str:
    """Indian number format: 2,45,000"""
    s = f"{abs(amount):.2f}"
    integer, decimal = s.split(".")
    n = len(integer)
    if n <= 3:
        return f"{integer}.{decimal}"
    result = integer[-3:]
    integer = integer[:-3]
    while integer:
        result = integer[-2:] + "," + result
        integer = integer[:-2]
    return f"{result}.{decimal}"


def draw_bank_statement(title: str, account_info: dict, rows: list, filename: str):
    """Render a mobile-banking screenshot PNG."""
    img = Image.new("RGB", (W, H), "#F5F7FA")
    draw = ImageDraw.Draw(img)

    # Header bar
    draw.rectangle([0, 0, W, 160], fill="#1A237E")
    f_title = load_font(38)
    f_sub   = load_font(26)
    f_small = load_font(22)
    f_body  = load_font(24)
    f_mono  = load_font(22)

    draw.text((40, 20),  title,                     font=f_title, fill="white")
    draw.text((40, 75),  account_info["bank"],       font=f_sub,   fill="#B3C0E8")
    draw.text((40, 110), account_info["acc_no"],     font=f_small, fill="#B3C0E8")
    draw.text((W-280, 90), f"Bal: Rs {fmt_inr(account_info['balance'])}", font=f_sub, fill="#FFD54F")

    # Column headers
    y = 185
    draw.rectangle([0, y, W, y+46], fill="#E8EAF6")
    draw.text((30,  y+10), "Date",     font=f_small, fill="#3949AB")
    draw.text((190, y+10), "Merchant", font=f_small, fill="#3949AB")
    draw.text((620, y+10), "Amount",   font=f_small, fill="#3949AB")
    draw.text((830, y+10), "Balance",  font=f_small, fill="#3949AB")

    y = 240
    for i, row in enumerate(rows):
        bg = "#FFFFFF" if i % 2 == 0 else "#F0F2FA"
        draw.rectangle([0, y, W, y+62], fill=bg)

        date_str, merchant, amount, direction, balance = row
        color = "#C62828" if direction == "Dr" else "#2E7D32"
        sign  = "-" if direction == "Dr" else "+"

        draw.text((30,  y+8),  date_str[:10],        font=f_mono,  fill="#37474F")
        draw.text((190, y+8),  merchant[:24],         font=f_body,  fill="#212121")
        draw.text((190, y+36), direction,             font=f_small, fill="#9E9E9E")
        draw.text((620, y+8),  f"{sign}Rs {fmt_inr(amount)}", font=f_body, fill=color)
        draw.text((830, y+8),  f"Rs {fmt_inr(balance)}",      font=f_mono, fill="#546E7A")

        y += 68
        if y > H - 80:
            break

    # Footer
    draw.rectangle([0, H-70, W, H], fill="#1A237E")
    draw.text((30, H-48), "Statement generated by MoneyMap Demo", font=f_small, fill="#B3C0E8")

    img.save(OUT / filename)
    print(f"  Saved {filename}")


def draw_upi_screenshot(rows: list, filename: str):
    """Render a UPI payment history PNG."""
    img = Image.new("RGB", (W, H), "#FFFFFF")
    draw = ImageDraw.Draw(img)

    # PhonePe-style header
    draw.rectangle([0, 0, W, 170], fill="#5F259F")
    f_title = load_font(42)
    f_sub   = load_font(26)
    f_small = load_font(22)
    f_body  = load_font(26)

    draw.text((40, 20),  "PhonePe",              font=f_title, fill="white")
    draw.text((40, 80),  "Payment History",      font=f_sub,   fill="#E1BEE7")
    draw.text((40, 120), "Rahul Sharma · UPI ID: rahul@phonepe", font=f_small, fill="#CE93D8")

    y = 195
    for i, row in enumerate(rows):
        bg = "#FAFAFA" if i % 2 == 0 else "#F3E5F5"
        draw.rectangle([0, y, W, y+90], fill=bg)

        date_str, merchant, amount, direction, note = row
        color = "#B71C1C" if direction == "paid" else "#1B5E20"
        sign  = "- Rs" if direction == "paid" else "+ Rs"
        arrow = "↑ Paid to" if direction == "paid" else "↓ Received from"

        draw.text((30,  y+8),  arrow,                          font=f_small, fill="#7B1FA2")
        draw.text((30,  y+32), merchant,                       font=f_body,  fill="#212121")
        draw.text((30,  y+62), date_str,                       font=f_small, fill="#9E9E9E")
        draw.text((W-320, y+30), f"{sign} {fmt_inr(amount)}", font=f_body,  fill=color)
        if note:
            draw.text((W-320, y+62), note, font=f_small, fill="#9E9E9E")

        y += 96
        if y > H - 80:
            break

    draw.rectangle([0, H-60, W, H], fill="#5F259F")
    draw.text((30, H-42), "Secured by PhonePe · NPCI UPI", font=f_small, fill="#CE93D8")

    img.save(OUT / filename)
    print(f"  Saved {filename}")


def make_credit_card_pdf(rows: list, outstanding: float, filename: str):
    doc = SimpleDocTemplate(str(OUT / filename), pagesize=A4,
                            leftMargin=20*mm, rightMargin=20*mm,
                            topMargin=20*mm, bottomMargin=20*mm)
    styles = getSampleStyleSheet()
    story  = []

    story.append(Paragraph("<b>HDFC Bank Credit Card Statement</b>", styles["Title"]))
    story.append(Paragraph("Card: **** **** **** 4821  |  Rahul Sharma", styles["Normal"]))
    story.append(Paragraph("Statement Period: 01-Jan-2025 to 31-Mar-2025", styles["Normal"]))
    story.append(Spacer(1, 8*mm))
    story.append(Paragraph(f"<b>Total Outstanding: Rs {fmt_inr(outstanding)}</b>", styles["Heading2"]))
    story.append(Spacer(1, 5*mm))

    header = ["Date", "Merchant / Description", "Amount (Rs)", "Type"]
    data   = [header] + rows
    t = Table(data, colWidths=[30*mm, 90*mm, 40*mm, 20*mm])
    t.setStyle(TableStyle([
        ("BACKGROUND", (0,0), (-1,0), colors.HexColor("#1A237E")),
        ("TEXTCOLOR",  (0,0), (-1,0), colors.white),
        ("FONTSIZE",   (0,0), (-1,0), 11),
        ("FONTSIZE",   (0,1), (-1,-1), 9),
        ("ROWBACKGROUNDS", (0,1), (-1,-1), [colors.white, colors.HexColor("#F0F2FA")]),
        ("GRID",       (0,0), (-1,-1), 0.3, colors.HexColor("#CCCCCC")),
        ("ALIGN",      (2,1), (2,-1), "RIGHT"),
    ]))
    story.append(t)

    story.append(Spacer(1, 8*mm))
    story.append(Paragraph("Minimum amount due: Rs 5,250  |  Due date: 15-Apr-2025", styles["Normal"]))
    story.append(Paragraph("This is a computer generated statement.", styles["Normal"]))

    doc.build(story)
    print(f"  Saved {filename}")


